/* paramsum - affiche le NOMBRE de parametres (pas leur somme!)
** IMPORTANT: affiche argc - 1 (nombre d'args sans argv[0])
** Ex: ./paramsum a b c -> 3 */
#include <unistd.h>

void	ft_putnbr(int n)
{
	char	c;

	if (n >= 10)
		ft_putnbr(n / 10);
	c = n % 10 + '0';
	write(1, &c, 1);
}

int	main(int argc, char **argv)
{
	(void)argv;
	ft_putnbr(argc - 1);
	write(1, "\n", 1);
	return (0);
}
